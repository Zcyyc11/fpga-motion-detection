# -*- coding: utf-8 -*-
"""Rewrite the two .bat launchers with CRLF + pure-ASCII content.

Why: cmd.exe (a) reads .bat in the OEM codepage so non-ASCII comments get
garbled into bogus commands, and (b) needs CRLF line endings -- with LF-only
endings it mis-parses `^` caret continuations, re-runs part of the script and
reports nonsense like "'n' is not recognized as an internal or external
command".  Both were live bugs in this repo.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

BUILD_BAT = r'''@echo off
rem ============================================================================
rem  Run the full Vivado build from source to bitstream.
rem
rem  NOTE 1: keep this file pure ASCII AND with CRLF line endings.
rem          cmd.exe reads .bat in the OEM codepage (GBK here), so non-ASCII
rem          comments get garbled; and LF-only endings make cmd mis-parse
rem          continuation lines (it then re-runs parts of the script and
rem          reports bogus errors like "'n' is not recognized").
rem          For the same reason every command below sits on ONE physical line:
rem          no ^ caret continuation.
rem  NOTE 2: settings64.bat must be called first, otherwise vivado.bat cannot
rem          find its own libraries.
rem
rem  Usage: build_vivado.bat [MODE_BG]   (0 = frame diff, 1 = background model)
rem  Log  : build/logs/vivado_build.log
rem ============================================================================
setlocal
rem Vivado location is configurable: set VIVADO_SETTINGS before calling.
rem No machine-specific default any more -- error out with guidance if unset.
if "%VIVADO_SETTINGS%"=="" (
    echo ERROR: VIVADO_SETTINGS is not set. Point it at the full path to settings64.bat on your machine.
    echo   e.g.  set VIVADO_SETTINGS=^<your Vivado install dir^>\Vivado\settings64.bat
    echo   or set env XILINX_VIVADO to the Vivado install directory.
    exit /b 9
)
call "%VIVADO_SETTINGS%" >nul 2>&1
if errorlevel 1 (
    echo ERROR: cannot load Vivado environment from "%VIVADO_SETTINGS%"
    exit /b 9
)

set SCRIPT_DIR=%~dp0
set ROOT=%SCRIPT_DIR%..\..
set LOGDIR=%ROOT%\build\logs
if not exist "%LOGDIR%" mkdir "%LOGDIR%"

set MODE_BG=%~1
if "%MODE_BG%"=="" set MODE_BG=0

cd /d "%ROOT%"

rem --- Clean the project directory with the OS, NEVER with Vivado ------------
rem Vivado's own "file delete -force" hangs when a stale file handle is present:
rem it pops a HIDDEN modal dialog and waits forever.  Measured: 10+ minutes
rem stuck, process idle at 15 MB with window title "OLEChannelWnd".
rem rmdir /s /q is native, dialog-free, and removed the same tree in ~2 s.
set PROJ=%ROOT%\build\vivado
if exist "%PROJ%" rmdir /s /q "%PROJ%"
if exist "%PROJ%" echo WARNING: could not fully remove "%PROJ%"

rem Log is written by this script itself: PowerShell redirection would emit
rem UTF-16, which is awkward to read back with plain text tools.
set LOG=%LOGDIR%\vivado_build.log
echo ==== vivado build start %DATE% %TIME% (MODE_BG=%MODE_BG%) ==== > "%LOG%"
call vivado.bat -mode batch -nojournal -nolog -source "%SCRIPT_DIR%build_vivado.tcl" -tclargs %MODE_BG% >> "%LOG%" 2>&1

set RC=%errorlevel%
echo ==== vivado build exit code %RC% ==== >> "%LOG%"
exit /b %RC%
'''

SIM_BAT = r'''@echo off
rem ============================================================================
rem  Run RTL simulation with Vivado xsim: xvlog -> xelab -> xsim.
rem
rem  NOTE 0: keep this file pure ASCII AND with CRLF line endings.
rem    LF-only endings make cmd.exe mis-parse the script; non-ASCII comments
rem    get garbled because cmd reads .bat in the OEM codepage (GBK here).
rem    sim/run_sim.bat is GENERATED by build/scripts/fix_bat_eol.py --
rem    edit that template, not this file.
rem
rem  NOTE 1 (why the environment has to be loaded at all):
rem    Without it, xelab still builds a snapshot fine, but xsim fails to start
rem    the engine with "Simulation engine failed to start ... -1073741515".
rem    0xC0000135 means DLL not found.  It looks like a design problem but is
rem    actually a missing environment.  Measured: the call fixes it.
rem
rem  NOTE 2 (Vivado location -- NO hard-coded path any more):
rem    Priority   1) VIVADO_SETTINGS = full path to settings64.bat
rem               2) XILINX_VIVADO   = install dir (settings64.bat sits in it)
rem               3) neither set     = assume this shell already has Vivado
rem    How to set it before calling (pick the one matching your shell):
rem      cmd         set VIVADO_SETTINGS=<your Vivado install dir>\Vivado\settings64.bat
rem      powershell  $env:VIVADO_SETTINGS = '<your Vivado install dir>\Vivado\settings64.bat'
rem      persistent  setx VIVADO_SETTINGS "<your Vivado install dir>\Vivado\settings64.bat"
rem    Same idea for XILINX_VIVADO (the install directory, not the .bat file).
rem
rem  Usage: run_sim.bat <top_module> <snapshot_name> <filelist>
rem
rem  Exit codes:  10 settings64.bat not found   11 settings64.bat failed to load
rem                12 xvlog/xelab/xsim not on PATH
rem                2  xvlog failed               3  xelab failed
rem                0  xsim ran (check the LOG CONTENT -- xsim.bat returns 0 even
rem                   when its engine never started, so the caller must judge
rem                   by the log, not by this exit code)
rem ============================================================================
setlocal
set VIV_SETTINGS=
if not "%VIVADO_SETTINGS%"=="" set VIV_SETTINGS=%VIVADO_SETTINGS%
if not "%XILINX_VIVADO%"=="" if "%VIV_SETTINGS%"=="" set VIV_SETTINGS=%XILINX_VIVADO%\settings64.bat

if "%VIV_SETTINGS%"=="" goto have_env
if not exist "%VIV_SETTINGS%" goto no_settings
call "%VIV_SETTINGS%" >nul 2>&1
if errorlevel 1 goto bad_settings
goto have_env

:no_settings
echo [ERROR] VIVADO_SETTINGS points at a file that does not exist:
echo           %VIV_SETTINGS%
echo   Fix it with ONE of these, then run again:
echo     cmd         set VIVADO_SETTINGS=<your Vivado install dir>\Vivado\settings64.bat
echo     powershell  $env:VIVADO_SETTINGS = '<your Vivado install dir>\Vivado\settings64.bat'
echo   Or set XILINX_VIVADO to the Vivado install directory instead.
exit /b 10

:bad_settings
echo [ERROR] settings64.bat exists but failed to load:
echo           %VIV_SETTINGS%
echo   Open it in a text editor and check the paths inside, or reinstall Vivado.
exit /b 11

:have_env
rem ---- All three tools must be reachable, otherwise fail loudly --------------
where xvlog.bat >nul 2>&1
if errorlevel 1 goto no_tools
where xelab.bat >nul 2>&1
if errorlevel 1 goto no_tools
where xsim.bat >nul 2>&1
if errorlevel 1 goto no_tools
goto run

:no_tools
echo [ERROR] Vivado simulation tools are not on PATH (xvlog / xelab / xsim).
echo           VIV_SETTINGS=%VIV_SETTINGS%
echo   Fix it with ONE of these, then run again:
echo     cmd         set VIVADO_SETTINGS=<your Vivado install dir>\Vivado\settings64.bat
echo     powershell  $env:VIVADO_SETTINGS = '<your Vivado install dir>\Vivado\settings64.bat'
echo     persistent  setx VIVADO_SETTINGS "<your Vivado install dir>\Vivado\settings64.bat"
echo   Or start from the Vivado Tcl shell / run settings64.bat yourself first,
echo   and just leave the variables unset.
exit /b 12

:run
set TOP=%~1
if "%TOP%"=="" set TOP=tb_md_pipeline
set SNAP=%~2
if "%SNAP%"=="" set SNAP=sim_%TOP%
set FL=%~3
if "%FL%"=="" set FL=files.f

cd /d "%~dp0"

echo === xvlog ===
call xvlog.bat -sv -f "%FL%"
if errorlevel 1 exit /b 2

echo === xelab ===
call xelab.bat -debug typical -timescale 1ns/1ps %TOP% -s %SNAP%
if errorlevel 1 exit /b 3

echo === xsim ===
call xsim.bat %SNAP% -runall
exit /b 0
'''


def write_crlf(path, text):
    data = text.replace('\r\n', '\n').replace('\n', '\r\n').encode('ascii')
    with open(path, 'wb') as f:
        f.write(data)
    return data


out = []
for rel, text in (('build/scripts/build_vivado.bat', BUILD_BAT),
                  ('sim/run_sim.bat', SIM_BAT)):
    p = os.path.join(ROOT, rel)
    data = write_crlf(p, text)
    bare_lf = data.count(b'\n') - data.count(b'\r\n')
    out.append('%s  bytes=%d  CRLF=%d  bareLF=%d  pure_ascii=%s'
               % (rel, len(data), data.count(b'\r\n'), bare_lf,
                  all(c < 128 for c in data)))

print('\n'.join(out))
